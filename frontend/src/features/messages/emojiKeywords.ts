const INDEX: Array<{ emoji: string; hay: string }> = PAIRS.map(([emoji, words]) => ({
  emoji,
  hay: words.join(" "),
}));

/** Search curated keywords; returns matching emoji glyphs (deduped). */
export function searchEmojisByKeyword(query: string, limit = 96): string[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const out: string[] = [];
  const seen = new Set<string>();
  for (const row of INDEX) {
    if (!isPickerEmojiAllowed(row.emoji)) continue;
    if (row.hay.includes(q) || q.split(/\s+/).every((t) => row.hay.includes(t))) {
      if (!seen.has(row.emoji)) {
        seen.add(row.emoji);
        out.push(row.emoji);
        if (out.length >= limit) break;
      }
    }
  }
  return out;
}
